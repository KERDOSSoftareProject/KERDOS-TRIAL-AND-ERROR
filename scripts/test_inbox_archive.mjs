assert.match(content(),/Mail 203/);
assert.equal(tree.root.findAllByType('time').length,1);
await act(async()=>{tree.root.findByProps({'aria-label':'Search emails'}).props.onChange({target:{value:'not-present'}});});
assert.match(content(),/No emails match/);
await act(async()=>{tree.root.findByProps({'aria-label':'Search emails'}).props.onChange({target:{value:''}});tree.root.findByProps({'aria-label':'Inbox vendors'}).props.onChange({target:{value:''}});tree.root.findByProps({'aria-label':'Sort emails'}).props.onChange({target:{value:'newest'}});});
