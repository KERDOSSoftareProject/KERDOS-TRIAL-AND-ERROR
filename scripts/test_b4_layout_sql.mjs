import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

const db=new PGlite();
const org='00000000-0000-4000-8000-000000000001';
const other='00000000-0000-4000-8000-000000000002';
const vendor='00000000-0000-4000-8000-000000000003';
const another='00000000-0000-4000-8000-000000000004';
const owner='00000000-0000-4000-8000-000000000005';
const outsider='00000000-0000-4000-8000-000000000006';
await db.exec(`create role authenticated; create role anon; create schema auth;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
create table public.organizations(id uuid primary key,settings jsonb);
create table public.vendors(id uuid primary key,organization_id uuid,is_active boolean);
create table public.organization_members(organization_id uuid,user_id uuid,role text);
insert into public.organizations values ('${org}','{"other":"preserved"}'),('${other}','{}');
insert into public.vendors values ('${vendor}','${org}',true),('${another}','${other}',true);
insert into public.organization_members values ('${org}','${owner}','owner');
grant usage on schema public,auth to authenticated,anon;
grant execute on function auth.uid() to authenticated,anon;`);
await db.exec(await readFile(new URL('../supabase/migrations/20261109140000_vendor_layout_answers.sql',import.meta.url),'utf8'));
await db.exec(`set role authenticated; set request.jwt.claim.sub='${owner}';`);
const call=(v=vendor,answers='{"5":"ignore"}')=>db.query('select public.kerdos_remember_vendor_layout($1,$2,$3,$4::jsonb) settings',[org,v,'item #|description|brand|pack|price|warehouse bin',answers]);
const first=await call();
assert.equal(first.rows[0].settings.vendorLayouts[vendor]['item #|description|brand|pack|price|warehouse bin']['5'],'ignore');
assert.equal(first.rows[0].settings.other,'preserved');
await call(vendor,'{"6":"brand"}');
await db.exec('reset role');
const row=await db.query(`select settings from public.organizations where id='${org}'`);
assert.deepEqual(row.rows[0].settings.vendorLayouts[vendor]['item #|description|brand|pack|price|warehouse bin'],{'5':'ignore','6':'brand'});
await db.exec(`set role authenticated; set request.jwt.claim.sub='${owner}'`);
await assert.rejects(call(another),/vendor_layout_access_denied/);
await assert.rejects(call(vendor,'{"5":"unknown"}'),/invalid_vendor_layout_answer/);
await db.exec(`set request.jwt.claim.sub='${outsider}'`);
await assert.rejects(call(),/vendor_layout_access_denied/);
await db.exec('reset role');
const final=await db.query(`select settings from public.organizations where id='${other}'`);
assert.deepEqual(final.rows[0].settings,{});
await db.close();
console.log('B4 vendor-layout SQL ownership, merge and validation passed');
