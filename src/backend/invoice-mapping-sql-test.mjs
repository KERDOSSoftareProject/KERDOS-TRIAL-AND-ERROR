import assert from "node:assert/strict";
import fs from "node:fs";
import {fileURLToPath} from "node:url";
import {PGlite} from "@electric-sql/pglite";

const db=new PGlite();
const org="00000000-0000-0000-0000-000000000001",user="00000000-0000-0000-0000-000000000002";
const vendor="00000000-0000-0000-0000-000000000003",item="00000000-0000-0000-0000-000000000004";
const listing="00000000-0000-0000-0000-000000000005";
await db.exec(`create schema auth; create role authenticated;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create table organization_members(organization_id uuid,user_id uuid,role text);
create table vendors(id uuid,organization_id uuid);
create table catalog_items(id uuid,organization_id uuid);
create table vendor_items(id uuid primary key default gen_random_uuid(),organization_id uuid,vendor_id uuid,vendor_item_code text,description text,pack_size text,price numeric,last_updated date,price_source text);
create table invoices(id uuid primary key default gen_random_uuid(),organization_id uuid,vendor_id uuid,total_amount numeric,raw_text text,invoice_date date,invoice_number text,status text,file_path text,file_name text);
create table item_mappings(organization_id uuid,catalog_item_id uuid,vendor_item_id uuid unique,confidence_score integer,match_method text,comparison_track text);
create table invoice_lines(invoice_id uuid,vendor_item_id uuid,vendor_item_code text,description text,unit_price numeric,line_total numeric,price_variance numeric,match_confidence integer,match_method text);
select set_config('request.jwt.claim.sub','${user}',false);
insert into organization_members values ('${org}','${user}','owner');
insert into vendors values ('${vendor}','${org}');
insert into catalog_items values ('${item}','${org}');
insert into vendor_items(id,organization_id,vendor_id,description,pack_size,price) values('${listing}','${org}','${vendor}','Bacon','10 LB',3.83);`);
const sql=fs.readFileSync(fileURLToPath(new URL("../../knowledge/migration_013_invoice_mapping.sql",import.meta.url)),"utf8");
await db.exec(sql);
const header={organization_id:org,vendor_id:vendor,total_amount:38.3,raw_text:"Bacon invoice",invoice_date:"2026-09-26",invoice_number:"A1"};
const line={vendor_item_id:listing,description:"Bacon",unit_price:3.83,line_total:38.3,catalog_item_id:item,catalog_confidence:75,catalog_track:"review"};
await db.query("select kerdos_record_invoice($1::jsonb,$2::jsonb)",[JSON.stringify(header),JSON.stringify([line])]);
assert.equal(Number((await db.query("select count(*) from item_mappings where vendor_item_id=$1",[listing])).rows[0].count),1,"existing vendor listing gets catalog link");
await db.query("select kerdos_record_invoice($1::jsonb,$2::jsonb)",[JSON.stringify({...header,invoice_number:"A2"}),JSON.stringify([line])]);
assert.equal(Number((await db.query("select count(*) from item_mappings where vendor_item_id=$1",[listing])).rows[0].count),1,"repeated invoice retains existing association");
const fresh={...line,vendor_item_id:null,vendor_item_code:"NEW",description:"Ham",pack_size:"5 LB"};
await db.query("select kerdos_record_invoice($1::jsonb,$2::jsonb)",[JSON.stringify({...header,invoice_number:"A3"}),JSON.stringify([{...fresh,create_vendor_item:true}])]);
assert.equal(Number((await db.query("select count(*) from item_mappings")).rows[0].count),2,"new invoice listing also linked");
await db.close();
console.log("Invoice catalog-link SQL tests passed");
