import {PGlite} from '@electric-sql/pglite';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';

const db=new PGlite();
const org='00000000-0000-0000-0000-000000000001',other='00000000-0000-0000-0000-000000000002';
const user='00000000-0000-0000-0000-000000000003',doc='00000000-0000-0000-0000-000000000004';
const invoice='00000000-0000-0000-0000-000000000005',item='00000000-0000-0000-0000-000000000006';
await db.exec(`create schema auth; create role authenticated;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create table organization_members(organization_id uuid,user_id uuid,role text);
create table import_documents(id uuid primary key,organization_id uuid,document_kind text,file_path text);
create table vendor_items(id uuid,organization_id uuid,price numeric,price_unavailable boolean,price_source text,import_row jsonb,price_quote_valid_until date,price_expired_at timestamptz);
create table price_history(id uuid,organization_id uuid,source_document_id uuid,price numeric);
create table invoices(id uuid primary key,organization_id uuid,file_path text);
create table invoice_lines(invoice_id uuid references invoices(id),description text);
create table item_mappings(vendor_item_id uuid,organization_id uuid);
select set_config('request.jwt.claim.sub','${user}',false);
insert into organization_members values('${org}','${user}','owner');
insert into import_documents values('${doc}','${org}','pricelist','${org}/sheet.csv'),('${other}','${other}','pricelist','${other}/sheet.csv');
insert into vendor_items values('${item}','${org}',40,false,'price_list','{"sourceDocumentId":"${doc}"}',null,null),('${other}','${other}',90,false,'price_list','{"sourceDocumentId":"${other}"}',null,null);
insert into price_history values('${doc}','${org}','${doc}',40),('${other}','${other}','${other}',90);
insert into item_mappings values('${item}','${org}');
insert into invoices values('${invoice}','${org}','${org}/invoice.pdf'),('${other}','${other}','${other}/invoice.pdf');
insert into invoice_lines values('${invoice}','Bacon'),('${other}','Milk');`);
const root=fileURLToPath(new URL('../../',import.meta.url));
await db.exec(fs.readFileSync(root+'/knowledge/migration_011_document_deletion.sql','utf8'));
await assert.rejects(db.query('select kerdos_delete_price_sheet($1,$2)',[other,other]),/access/);
const removed=await db.query('select kerdos_delete_price_sheet($1,$2) as result',[org,doc]);
assert.equal(removed.rows[0].result.file_path,`${org}/sheet.csv`);
assert.equal((await db.query('select price from vendor_items where id=$1',[item])).rows[0].price,null);
assert.equal((await db.query('select count(*) from item_mappings')).rows[0].count,1);
assert.equal((await db.query('select count(*) from price_history')).rows[0].count,1);
assert.equal((await db.query('select count(*) from import_documents')).rows[0].count,1);
const deletedInvoice=await db.query('select kerdos_delete_invoice_record($1,$2) as result',[org,invoice]);
assert.equal(deletedInvoice.rows[0].result.file_path,`${org}/invoice.pdf`);
assert.equal((await db.query('select count(*) from invoices')).rows[0].count,1);
assert.equal((await db.query('select count(*) from invoice_lines')).rows[0].count,1);
console.log('Document deletion SQL passed: tenant isolation, source cleanup, mapping retention and atomic invoice lines.');
