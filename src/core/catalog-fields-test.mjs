import assert from "node:assert/strict";
import {knownItemChanges,rememberImportRow,importResolutions,catalogRowEvidence,unitChoices,CATALOG_COLUMNS} from "./catalog-fields.js";
import {prepareCatalogCorrection} from "../services/catalog-rows.js";
import {explainImportRow} from "./import-evidence.js";
import {resolveQuoteBasis} from "./quote-basis.js";
import {configureVocabulary,casePriceFromQuote,priceBasisFor} from "../procurement.js";
const prior={id:"vi1",organization_id:"o1",vendor_id:"vendor1",vendor_item_code:"001001",description:"Bacon frozen",brand:"My brand",pack_size:"1/15 LB",selling_unit:"LB",price_basis:"measure",price:3.83,row_revision:2};
const mapping={id:"m1",vendor_item_id:"vi1",catalog_item_id:"ci1",organization_id:"o1",comparison_track:"exact",confidence_score:100};
const item={id:"ci1",category_id:"meat",master_item_number:2010,name:"Bacon frozen"};
const category={id:"meat",name:"Meat"};
const incoming={code:"001001",description:"Bacon frozen",brand:"",packSize:null,sellingUnit:null,price:3.00,sourceLine:"001001 3.00"};
const known=rememberImportRow(incoming,prior,mapping);
assert.equal(known.description,prior.description);
assert.equal(known.packSize,prior.pack_size);
assert.equal(known.brand,prior.brand);
assert.equal(known.price,3);
assert.equal(known.knownVendorItem,true);
assert.equal(resolveQuoteBasis(known,prior).sellingUnit,"LB");
assert.equal(casePriceFromQuote(known.price,"measure","LB",known.packSize),45);
const evidence=explainImportRow(incoming,{vendor:{id:"vendor1",name:"Vendor One"},catalogItems:[item],categories:[category],vendorItems:[prior],mappings:[mapping]});
assert.equal(evidence.itemNumber.value,2010);
assert.equal(evidence.itemNumber.accuracy,90);
assert.equal(evidence.product.value,"Bacon frozen");
assert.equal(evidence.unitCost.value,3);
assert.equal(evidence.knownItem,true);
const foreignVendor=explainImportRow(incoming,{vendor:{id:"vendor2",name:"Vendor Two"},catalogItems:[item],vendorItems:[prior],mappings:[mapping]});
assert.equal(foreignVendor.knownItem,false,"same code from another vendor is a new identity");
assert.equal(rememberImportRow({...incoming,code:"1001"},prior,mapping).knownVendorItem,undefined,"leading zeros are significant");
const corrected={...prior,field_resolutions:{description:{value:"Bacon frozen",sourceValue:"BCN FRZ"}},import_row:{row:{description:"BCN FRZ"}}};
assert.equal(rememberImportRow({...incoming,description:"BCN FRZ"},corrected).description,"Bacon frozen");
const stored=importResolutions({description:"Bacon frozen",manualFields:["description"],originalFields:{description:"BCN FRZ"}},{});
assert.equal(stored.description.sourceValue,"BCN FRZ");
assert.equal(stored.description.value,"Bacon frozen");
const pending=prepareCatalogCorrection({organizationId:"o1",vendorItem:prior,mapping,patch:{pack_size:"",brand:""}});
assert.equal(pending.priceAvailable,false);
assert.equal(pending.expectedRevision,2);
assert.equal(pending.patch.brand,"");
assert.throws(()=>prepareCatalogCorrection({organizationId:"other",vendorItem:prior,mapping,patch:{price:3}}),/organization/);
assert.throws(()=>prepareCatalogCorrection({organizationId:"o1",vendorItem:prior,mapping,patch:{price:-3}}),/positive/);
const unitChanged=prepareCatalogCorrection({organizationId:"o1",vendorItem:prior,mapping,patch:{selling_unit:"GAL"}});
assert.equal(unitChanged.priceAvailable,false,"volume quote cannot turn into a weight price");
const rowEvidence=vi=>catalogRowEvidence({vendorItem:vi,item,mapping,vendor:{name:"V"},category});
assert.equal(rowEvidence({...prior,price:40,selling_unit:"CASE",pack_size:"4/1 GAL"}).unitCost.value,10);
assert.equal(rowEvidence({...prior,price:40,selling_unit:"CASE",pack_size:"4/1 GAL"}).unitCost.unit,"GAL");
assert.equal(rowEvidence({...prior,price:3,selling_unit:"EACH",pack_size:"4/10 OZ"}).unitCost.value,.3);
assert.equal(rowEvidence({...prior,selling_unit:null}).unitCost.value,null);
assert.equal(rowEvidence({...prior,brand:null}).brand.accuracy,null);
assert.equal(priceBasisFor("DOZ").basis,"measure");
assert.equal(casePriceFromQuote(.93,"measure","DOZ","1/30 DZ"),27.9);
configureVocabulary([{kind:"unit",term:"sheet",canonical:"SHEET"}]);
assert.ok(unitChoices([{kind:"unit",term:"sheet",canonical:"SHEET"}]).some(u=>u.value==="sheet"));
assert.equal(casePriceFromQuote(2,"measure","sheet","100 sheet"),200);
configureVocabulary([]);
assert.deepEqual(CATALOG_COLUMNS.map(c=>c[0]),["itemNumber","vendor","vendorItemNumber","category","itemName","product","brand","pack","price","sellingUnit","unitCost"]);
console.log("KERDOS new-item and remembered-item workflow tests passed");

const changedWords={...incoming,description:"Vendor changed the label"};
const reviewed=rememberImportRow(changedWords,prior,mapping);
assert.equal(reviewed.knownVendorItem,true);
assert.equal(reviewed.description,prior.description,"oversight does not change saved identity");
assert.equal(reviewed.priceNeedsReview,true);
assert.equal(reviewed.changes[0].field,"description");
const pendingSource={...prior,import_row:{baseline:{description:"Bacon frozen",packSize:"1/15 LB"},row:changedWords,reviewRequired:true}};
assert.equal(knownItemChanges(changedWords,pendingSource).length,1,"a second unapproved sheet cannot silently become the accepted baseline");
assert.equal(knownItemChanges({...incoming,description:" BACON, FROZEN "},prior).length,0,"formatting does not need review");
assert.equal(knownItemChanges({...incoming,description:""},prior).length,0,"code-and-price sheets can omit known descriptions");
assert.equal(knownItemChanges({...incoming,sellingUnit:"CASE"},prior)[0].field,"sellingUnit");
assert.equal(knownItemChanges({...incoming,packSize:"1/20 LB"},prior)[0].field,"packSize");
assert.equal(knownItemChanges({...incoming,brand:"Other brand"},prior)[0].field,"brand");

const restaurantUnits=unitChoices([{kind:"unit",term:"yards",canonical:"YD"},{kind:"packaging",term:"bunches"}],false,"Restaurant");
assert.deepEqual(restaurantUnits.map(u=>u.value),["CASE","EACH","LB","OZ","GAL","QT","PT","FLOZ","KG","G","L","ML","DOZ"]);
assert.ok(!unitChoices([],true,"Restaurant").some(u=>["CASE","EACH","FT","IN","YD","M","CM","MM"].includes(u.value)));
assert.ok(unitChoices([],false,"Construction").some(u=>u.value==="YD"),"nonfood industries retain length units");
